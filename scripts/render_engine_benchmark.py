#!/usr/bin/env python3
"""Render measured rows and explicit failures; keep raw runs in the input JSON."""
import argparse
import csv
import json
from pathlib import Path
import statistics


NAMES = {"llama32-1b": "Llama 3.2 1B", "qwen35-2b": "Qwen3.5 2B",
         "gpt-oss-20b": "GPT-OSS 20B", "glm47-flash": "GLM 4.7 Flash"}


def deployment(row):
    if row["status"] == "error":
        return "échec"
    if row["status"] != "ok":
        return "mesure invalide"
    if row["backend"] == "cpu":
        return "CPU"
    if row["engine"] == "ollama":
        models = row.get("loaded_model", {}).get("models", [])
        if models:
            return "GPU + CPU" if models[0]["size_vram"] < models[0]["size"] else "GPU"
    if row["engine"] == "rbitnet":
        return "CUDA + opérations CPU"
    if any("tensor overrides to CPU" in line for line in row.get("offload_evidence", [])):
        return "GPU + CPU"
    for line in row.get("offload_evidence", []):
        import re
        match = re.search(r"offloaded (\d+)/(\d+) layers", line)
        if match:
            return "GPU + CPU" if match[1] != match[2] else "GPU"
    return "GPU demandé"


def summary_row(row):
    samples = row.get("samples", [])
    valid = row["status"] == "ok" and row.get("prompt_alignment_verified", False)
    return {"model": row["model"], "engine": row["engine"], "backend": row["backend"],
            "status": row["status"], "deployment": deployment(row),
            "decode_tokens_per_second_median": row.get("median_decode_tokens_per_second") if valid else None,
            "decode_tokens_per_second_min": min((s["decode_tokens_per_second"] for s in samples), default=None) if valid else None,
            "decode_tokens_per_second_max": max((s["decode_tokens_per_second"] for s in samples), default=None) if valid else None,
            "wall_ms_median": row.get("median_wall_ms") if valid else None,
            "wall_tokens_per_second_median": statistics.median(s["wall_tokens_per_second"] for s in samples) if valid else None,
            "prefill_ms_median": statistics.median(s["prefill_ms"] for s in samples) if valid else None,
            "first_content_ms_single_probe": row.get("stream_probe", {}).get("first_content_ms"),
            "quality_passes": row.get("quality_passes") if valid else None,
            "peak_process_tree_rss_gib": row.get("memory", {}).get("peak_process_tree_rss_bytes", 0) / 2**30 if valid else None,
            "gpu_global_peak_delta_mib": row.get("memory", {}).get("gpu_global_peak_delta_mib") if valid else None,
            "error": row.get("error", "")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--plot", action="store_true")
    args = parser.parse_args()
    report = json.loads(args.input.read_text(encoding="utf-8"))
    rows = [summary_row(row) for row in report["rows"]]
    if not rows:
        parser.error("No benchmark rows; inspect fixture_errors in the input JSON")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "summary.json").write_text(json.dumps({"environment": report["environment"], "protocol": report["protocol"], "rows": rows}, indent=2, ensure_ascii=False), encoding="utf-8")
    with (args.output_dir / "summary.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = ["<!-- Generated by scripts/render_engine_benchmark.py; methodology belongs in README.md. -->", ""]
    for backend, title in [("cpu", "CPU"), ("gpu", "GPU / déport CPU")]:
        lines += [f"## {title}", "", "| Modèle | Moteur | Déploiement observé | Décodage médian (tok/s) | Requête médiane (ms) | RAM pic (Gio) | VRAM delta pic (Mio) | Réponses strictes |", "|---|---|---|---:|---:|---:|---:|---:|"]
        for model in report["models"]:
            for engine in ["rbitnet", "ollama", "llama.cpp"]:
                row = next((r for r in rows if r["model"] == model["id"] and r["engine"] == engine and r["backend"] == backend), None)
                if row is None:
                    continue
                def number(key, digits=1):
                    return f"{row[key]:.{digits}f}" if row[key] is not None else "—"
                quality = f"{row['quality_passes']}/3" if row["quality_passes"] is not None else "—"
                lines.append(f"| {NAMES.get(row['model'], row['model'])} | {engine} | {row['deployment']} | {number('decode_tokens_per_second_median')} | {number('wall_ms_median')} | {number('peak_process_tree_rss_gib', 2)} | {number('gpu_global_peak_delta_mib', 0)} | {quality} |")
        lines += [""]
    (args.output_dir / "tables.md").write_text("\n".join(lines), encoding="utf-8")
    if args.plot:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, axes = plt.subplots(1, 2, figsize=(14, 5), sharey=True)
        colors = {"rbitnet": "#9e4050", "ollama": "#2f7187", "llama.cpp": "#d09b39"}
        models = [model["id"] for model in report["models"]]
        for ax, backend in zip(axes, ["cpu", "gpu"]):
            for index, engine in enumerate(colors):
                for position, model in enumerate(models):
                    row = next((r for r in rows if r["model"] == model and r["engine"] == engine and r["backend"] == backend), None)
                    x = position + (index - 1) * 0.25
                    if row and row["decode_tokens_per_second_median"] is not None:
                        value = row["decode_tokens_per_second_median"]
                        ax.bar(x, value, width=0.23, color=colors[engine])
                        ax.text(x, value * 1.12, f"{value:.1f}", ha="center", fontsize=8)
                    else:
                        label = "non testé" if row is None else ("échec" if row["status"] == "error" else "invalide")
                        ax.text(x, 0.62, label, rotation=90, ha="center", va="bottom", fontsize=8, color=colors[engine])
            ax.set_title("CPU" if backend == "cpu" else "GPU / déport CPU")
            ax.set_xticks(range(len(models)), [NAMES.get(m, m) for m in models], fontsize=9)
            ax.set_yscale("log")
            ax.set_ylim(0.5, max(10, max((r["decode_tokens_per_second_max"] or 0 for r in rows), default=10)) * 2)
            ax.grid(axis="y", which="major", alpha=0.2)
            ax.set_axisbelow(True)
        axes[0].set_ylabel("Décodage médian, tokens/s — échelle logarithmique")
        from matplotlib.patches import Patch
        axes[0].legend(handles=[Patch(color=color, label=engine) for engine, color in colors.items()
                              if any(row["engine"] == engine for row in rows)], frameon=False)
        protocol = report["protocol"]
        fig.suptitle(f"Même GGUF par modèle · {protocol['repeats']} requêtes de {protocol['max_output_tokens']} tokens", fontsize=13)
        fig.text(0.5, 0.01, "Échec = aucune vitesse comparable. Ce test court ne mesure pas la qualité générale des modèles.", ha="center", fontsize=9)
        fig.tight_layout(rect=[0, 0.05, 1, 0.93])
        fig.savefig(args.output_dir / "throughput.png", dpi=180)
        plt.close(fig)


if __name__ == "__main__":
    main()
